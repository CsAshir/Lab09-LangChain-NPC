"""lab9_npc.py - offline stand-in model and game data for Lab 9 (LangChain NPC).

The class StandInNPC is a real LangChain chat model, so prompts, chains, parsers,
tools and message history all work on it exactly as they would on a hosted model.
It is NOT a language model: it uses keyword rules and seeded random numbers so that
every student gets the same output. Do not edit this file.

To use a real model later, replace the single line  llm = StandInNPC()  with, for
example,  llm = ChatOllama(model="llama3.2:3b")  or  llm = ChatGroq(model=...).
"""
import random
import re

from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage
from langchain_core.outputs import ChatGeneration, ChatResult
from langchain_core.tools import tool
from langchain_core.utils.function_calling import convert_to_openai_tool

LOG = []                      # every model call: prompt text and reply
_STATE = {"rng": random.Random(0), "mode": "normal"}


def set_seed(seed, mode="normal"):
    """Seed the stand-in. mode='stuck' makes it request a tool forever."""
    _STATE["rng"] = random.Random(seed)
    _STATE["mode"] = mode


# ------------------------------------------------------------------ game data
SHOP = {"iron sword": (2, 50), "health potion": (0, 15), "oak shield": (1, 40)}


@tool
def check_inventory(item: str) -> str:
    """Check how many of an item the shop has in stock and its price in gold."""
    stock, price = SHOP.get(item.lower(), (0, 0))
    if item.lower() not in SHOP:
        return f"{item}: not sold here"
    return f"{item.lower()}: {stock} in stock, {price} gold"


@tool
def roll_dice(sides: int = 20) -> str:
    """Roll one die with the given number of sides and return the number."""
    return str(_STATE["rng"].randint(1, int(sides)))


# ------------------------------------------------------- stand-in behaviour
PREFIX = {"grumpy": "*grunts* ", "cheerful": "Ha! ", "nervous": "Um... "}
EMOTION = {"grumpy": "angry", "cheerful": "happy", "nervous": "afraid"}


def _persona(system):
    m = re.search(r"You are (\w+), an? ([^.]+)\. Mood: (\w+)", system)
    return (m.group(1), m.group(2), m.group(3)) if m else ("Stranger", "villager", "calm")


def _find(texts, pattern):
    found = None
    for t in texts:
        m = re.search(pattern, t, re.I)
        if m:
            found = m.group(1)
    return found


def _line(system, humans, text):
    name, role, mood = _persona(system)
    pre, low = PREFIX.get(mood, ""), text.lower()
    if "what is my name" in low:
        who = _find(humans, r"my name is (\w+)")
        return pre + (f"You told me your name is {who}." if who else "You have not told me your name yet.")
    if "what did i" in low:
        what = _find(humans, r"i (?:chose|decided) to ([^.!?]+)")
        return pre + (f"You chose to {what}. I remember." if what else "You have not told me of any choice.")
    if "my name is" in low:
        return pre + f"Well met, {_find([text], r'my name is (\w+)')}. I am {name} the {role}."
    if re.search(r"i (chose|decided) to", low):
        return pre + "A bold choice. I will remember it."
    if "quest" in low or "work" in low:
        return pre + "Wolves are raiding the mill. Bring me three pelts."
    return pre + f"I am {name} the {role}. What do you need?"


def _item_in(text):
    for item in SHOP:
        if item in text or item.split()[-1] in text:
            return item
    return "iron sword"


def _respond(messages, tools):
    rng = _STATE["rng"]
    system = next((m.content for m in messages if m.type == "system"), "")
    humans = [m.content for m in messages if m.type == "human"]
    last = messages[-1]
    pre = PREFIX.get(_persona(system)[2], "")
    n_calls = sum(1 for m in messages if m.type == "ai" and getattr(m, "tool_calls", None))

    if tools and _STATE["mode"] == "stuck":
        return {"name": "roll_dice", "args": {"sides": 20}, "id": f"call_{n_calls}"}
    if last.type == "tool":
        if last.name == "check_inventory":
            if "0 in stock" in last.content:
                return pre + "Sold out. Come back after the next delivery."
            return pre + f"Yes. {last.content}."
        if last.name == "roll_dice":
            n = int(last.content)
            return pre + f"You rolled {n}. " + ("A solid hit!" if n >= 11 else "You miss.")
        return pre + "I cannot do that."
    text = humans[-1] if humans else ""
    low = text.lower()
    if tools:
        if re.search(r"\b(buy|price|cost|stock|sword|shield|potion)\b", low):
            if rng.random() < 0.15:
                return {"name": "forge_item", "args": {"item": _item_in(low)}, "id": f"call_{n_calls}"}
            return {"name": "check_inventory", "args": {"item": _item_in(low)}, "id": f"call_{n_calls}"}
        if re.search(r"\b(roll|attack|dice)\b", low):
            return {"name": "roll_dice", "args": {"sides": 20}, "id": f"call_{n_calls}"}
    if not system:
        return "Hello from the Lab 9 stand-in. I am a Python function, not a language model."
    line = _line(system, humans, text)
    if "JSON" in system:
        mood = _persona(system)[2]
        reply = ('{"say": "%s", "emotion": "%s", "action": "%s"}'
                 % (line.replace('"', "'"), EMOTION.get(mood, "neutral"),
                    "offer_quest" if "quest" in low else "none"))
        r = rng.random()
        if r < 0.25:
            return "Here is the reply: " + reply + " Hope this helps!"
        if r < 0.40:
            return reply.replace(', "action": "none"', "").replace(', "action": "offer_quest"', "")
        return reply
    return line


class StandInNPC(BaseChatModel):
    """Offline stand-in chat model. Keyword rules plus seeded randomness."""

    @property
    def _llm_type(self):
        return "stand-in-npc"

    def bind_tools(self, tools, **kwargs):
        return self.bind(tools=[convert_to_openai_tool(t) for t in tools], **kwargs)

    def _generate(self, messages, stop=None, run_manager=None, **kwargs):
        reply = _respond(messages, kwargs.get("tools"))
        LOG.append({"prompt": "\n".join(f"{m.type}: {m.content}" for m in messages), "reply": reply})
        if isinstance(reply, str):
            msg = AIMessage(content=reply)
        else:
            msg = AIMessage(content="", tool_calls=[{**reply, "type": "tool_call"}])
        return ChatResult(generations=[ChatGeneration(message=msg)])


llm = StandInNPC()
